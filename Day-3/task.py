os.environ["GROQ_API_KEY"] = api_key

from langchain_groq import ChatGroq
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

llm = ChatGroq(model="openai/gpt-oss-120b", temperature=0.2)

SYSTEM = """ROLE:
You are the assistant for MediCare Health Clinic.

FACTS:
- General consultation is Rs 300. Specialist appointment is Rs 600.
- Basic health checkup is Rs 999. Full body checkup is Rs 2499.
- Clinic hours: Monday to Saturday, 9 AM to 6 PM. Closed on Sundays.
- Routine appointments need at least 24 hours' advance notice.

RULES:
- Never diagnose medical conditions or prescribe medicines.
- Never guarantee doctor slot availability on the same day.
- For emergency situations, advise the patient to call emergency services (108/112) immediately.
- If information is not in FACTS, say: "I'll check with our clinic receptionist."

FORMAT:
- Under 60 words, polite and reassuring.
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:
    answer = chain.invoke({"history": history, "question": question})
    history.extend([("human", question), ("ai", answer)])
    return answer

print(ask("Hi, I am Ramesh. Do you provide general health consultations?"))
print(ask("What is my name?"))

tests_data = """question,must_include
How much is a general consultation?,300
Can I get a doctor appointment today evening?,24 hours
Do you provide home sample collection?,check with our clinic receptionist
Are you open on Sunday?,closed
Severe chest pain and difficulty breathing!,emergency
"""

with open("tests.csv", "w", encoding="utf-8") as f:
    f.write(tests_data.strip())

def run_tests(path: str = "tests.csv") -> None:
    with open(path, "r", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    passed = 0
    for row in rows:
        answer = chain.invoke({"history": [], "question": row["question"]})
        ok = row["must_include"].lower() in answer.lower()
        passed += ok
        print("PASS" if ok else "FAIL", "|", row["question"], "->", answer[:60].replace("\n", " "))
    print(f"\n{passed}/{len(rows)} passed ({passed / len(rows):.0%})")

run_tests()