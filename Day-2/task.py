history = [{"role": "system", "content": SYSTEM}]
MAX_TURNS = 6

def chat(user_text: str) -> str:
    history.append({"role": "user", "content": user_text})
    recent_messages = [history[0]] + history[1:][-MAX_TURNS:]
    try:
        response = client.chat.completions.create(
            model="openai/gpt-oss-120b",
            temperature=0.2,
            messages=recent_messages
        )
        reply = response.choices[0].message.content
    except RateLimitError:
        reply = "We are busy. Please try again in a minute."
    except APIConnectionError:
        reply = "Cannot reach server. Please try again shortly."
    except Exception:
        reply = "An error occurred. Please contact the clinic directly."

    history.append({"role": "assistant", "content": reply})
    return reply

print(chat("Hello, my name is Anita."))
print(chat("What are your clinic hours and how much is a general consultation?"))
print(chat("What is my name and what service did I just ask about?"))