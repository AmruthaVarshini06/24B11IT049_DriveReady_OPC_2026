def classify_patient_message(message: str) -> str:
    few_shot_messages = [
        {"role": "system", "content": "Classify the message into one category: appointment, pricing, emergency, or feedback. Return ONLY the category word."},
        {"role": "user", "content": "Can I book a doctor visit for tomorrow 10 am?"},
        {"role": "assistant", "content": "appointment"},
        {"role": "user", "content": "How much does a full body checkup cost?"},
        {"role": "assistant", "content": "pricing"},
        {"role": "user", "content": "Severe chest pain and difficulty breathing!"},
        {"role": "assistant", "content": "emergency"},
        {"role": "user", "content": message}
    ]
    response = client.chat.completions.create(
        model="openai/gpt-oss-120b",
        temperature=0.0,
        messages=few_shot_messages
    )
    return response.choices[0].message.content.strip().lower()

print(classify_patient_message("Do you have slots for general consultation?"))
print(classify_patient_message("Patient is having breathing trouble"))

def extract_booking_json(user_text: str) -> dict:
    prompt = """Extract the appointment request from the patient's message.
Return ONLY valid JSON with these keys:
- patient_name (str)
- service_requested (str)
- preferred_date (str)
- is_emergency (bool)
"""
    response = client.chat.completions.create(
        model="openai/gpt-oss-120b",
        temperature=0.1,
        messages=[
            {"role": "system", "content": prompt},
            {"role": "user", "content": user_text}
        ]
    )
    content = response.choices[0].message.content.strip()
    if content.startswith("```"):
        content = content.replace("```json", "").replace("```", "").strip()
    return json.loads(content)

