def log_call(func):
    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        result = func(*args, **kwargs)
        print(f"[log] {func.__name__}{args} -> {result!r}")
        return result
    return wrapper

@log_call
def calculate_service_fee(service_name: str, count: int = 1) -> int:
    key = service_name.lower().strip()
    return SERVICES_CATALOG[key] * count

print(calculate_service_fee("basic health checkup", 2))

