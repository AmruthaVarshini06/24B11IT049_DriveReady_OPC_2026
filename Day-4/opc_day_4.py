import os
from google.colab import userdata, auth
from typing import Literal
from pydantic import BaseModel, Field
from langchain.tools import tool
from langchain_groq import ChatGroq
from langchain.agents import create_agent

try:
    api_key = userdata.get("GROQ_API_KEY")
except Exception:
    try:
        api_key = userdata.get("GROK_API_KEY")
    except Exception:
        api_key = ""

os.environ["GROQ_API_KEY"] = api_key

llm = ChatGroq(model="openai/gpt-oss-120b", temperature=0.2, max_retries=3)

auth.authenticate_user()
import gspread
from google.auth import default
creds, _ = default()
gc = gspread.authorize(creds)
try:
    sh = gc.open("MediCare Clinic Appointments")
except Exception:
    sh = gc.create("MediCare Clinic Appointments")

ws = sh.sheet1
if not ws.get_all_values():
    ws.append_row(["name", "service", "date", "is_emergency", "fee"])
print("Sheet ready:", sh.url)

SERVICES = {
    "general consultation": 300,
    "specialist appointment": 600,
    "basic health checkup": 999,
    "full body checkup": 2499,
    "blood test": 250
}

HOURS = {
    "monday": "9 am to 6 pm",
    "tuesday": "9 am to 6 pm",
    "wednesday": "9 am to 6 pm",
    "thursday": "9 am to 6 pm",
    "friday": "9 am to 6 pm",
    "saturday": "9 am to 6 pm",
    "sunday": "closed"
}

class Appointment(BaseModel):
    name: str = Field(description="Patient's full name")
    service: Literal[
        "general consultation",
        "specialist appointment",
        "basic health checkup",
        "full body checkup",
        "blood test"
    ] = Field(description="Clinic service requested")
    date: str = Field(description="Appointment date requested by patient")
    is_emergency: bool = Field(description="Whether the request is a medical emergency")

@tool
def get_service_fee(service: str) -> str:
    """Get the standard fee in rupees for a clinic service.

    Args:
        service: Clinic service name, e.g. "general consultation", "basic health checkup"
    """
    fee = SERVICES.get(service.lower().strip())
    if fee is None:
        return f"'{service}' is not recognized. We offer: {', '.join(SERVICES)}."
    return f"Fee for {service} is Rs {fee}."

@tool
def check_clinic_hours(day: str) -> str:
    """Check the clinic operational hours for a specific day of the week, e.g. "sunday" or "monday"."""
    hours = HOURS.get(day.lower().strip())
    if hours is None:
        return f"'{day}' is not a valid day of the week."
    if hours == "closed":
        return f"MediCare Health Clinic is closed on {day}."
    return f"MediCare Health Clinic is open from {hours} on {day}."

@tool
def log_appointment(name: str, service: str, date: str, is_emergency: bool) -> str:
    """Save a confirmed clinic appointment or test booking to the Appointments sheet.
    Use only when patient name, service, and appointment date are clearly provided."""
    try:
        appt = Appointment(
            name=name,
            service=service.lower().strip(),
            date=date,
            is_emergency=is_emergency
        )
    except Exception as e:
        return f"Could not log appointment: {e}. Ask patient to clarify details."

    fee = SERVICES[appt.service]
    ws.append_row([
        appt.name,
        appt.service,
        appt.date,
        "yes" if appt.is_emergency else "no",
        fee
    ])
    return f"Appointment logged: {appt.service} for {appt.name} on {appt.date}, Fee Rs {fee}."

SYSTEM = """ROLE:   You are the friendly appointment assistant for MediCare Health Clinic.
FACTS:  Routine appointments need 24 hours' notice. Clinic is closed on Sundays.
RULES:  Always use get_service_fee for fees and check_clinic_hours for timings; never guess them.
        Before log_appointment, ensure you have patient name, service, and date; ask if missing.
        Never diagnose or prescribe. If emergency symptoms appear, advise calling 108/112 immediately.
        After logging an appointment, read the details back with the fee.
FORMAT: Under 60 words, polite, reassuring."""

agent = create_agent(
    model=llm,
    tools=[get_service_fee, check_clinic_hours, log_appointment],
    system_prompt=SYSTEM
)

history = []

def chat(text: str) -> str:
    global history
    try:
        result = agent.invoke({"messages": history + [{"role": "user", "content": text}]})
        history = result["messages"]
        return history[-1].content
    except Exception as e:
        print("Agent error:", e)
        return "Sorry, I am busy. Please try again in a minute."

print(chat("Are you open on Sunday? How much is a basic health checkup?"))
print(chat("I am Ramesh Kumar. Please book a basic health checkup for Friday."))